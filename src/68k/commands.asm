
; ------------------------------------------------------------------------------
; Plays a given sample
; ------------------------------------------------------------------------------
; INPUT:
;		d0	.b		sample id (>$81)
;
; EXAMPLES:
;		move.b	#$81, d0
;		jsr		MegaPCM_PlaySample
;
;		move.b	#mysample.id, d0	; if sample has a label in sample table
;		jsr		MegaPCM_PlaySample
; ------------------------------------------------------------------------------

MegaPCM_PlaySample:
	MPCM_play	d0
	rts

; ------------------------------------------------------------------------------
; Pauses current sample playback
; ------------------------------------------------------------------------------

MegaPCM_PausePlayback:
	MPCM_pause
	rts

; ------------------------------------------------------------------------------
; Unpauses playback
; ------------------------------------------------------------------------------

MegaPCM_UnpausePlayback:
	MPCM_unpause
	rts

; ------------------------------------------------------------------------------
; Stops all playback
; ------------------------------------------------------------------------------

MegaPCM_StopPlayback:
	MPCM_stop
	rts

; ------------------------------------------------------------------------------
; Sets panning for normal (non-SFX) samples
; ------------------------------------------------------------------------------
; INPUT:
;		d0	.b		LR-pan ($40, $80 or $C0)
; ------------------------------------------------------------------------------

MegaPCM_SetPan:
	MPCM_setPan	d0
	rts

; ------------------------------------------------------------------------------
; Sets panning for SFX samples (added with FLAGS_SFX)
; ------------------------------------------------------------------------------
; INPUT:
;		d0	.b		LR-pan ($40, $80 or $C0)
; ------------------------------------------------------------------------------

MegaPCM_SetSFXPan:
	MPCM_setSfxPan d0
	rts

; ------------------------------------------------------------------------------
; Sets volume for normal (non-SFX) samples
; ------------------------------------------------------------------------------
; INPUT:
;		d0	 .b		volume level (0 = max .. $F = min)
; ------------------------------------------------------------------------------

MegaPCM_SetVolume:
	MPCM_setVol	d0
	rts

; ------------------------------------------------------------------------------
; Sets volume for SFX samples (added with FLAGS_SFX)
; ------------------------------------------------------------------------------
; INPUT:
;		d0	 .b		volume level (0 = max .. $F = min)
; ------------------------------------------------------------------------------

MegaPCM_SetSFXVolume:
	MPCM_setSfxVol	d0
	rts

; ------------------------------------------------------------------------------
; Updates pitch for the currently playing sample
; ------------------------------------------------------------------------------
; INPUT:
;		d0	.b		sample pitch (0 = 0% base rate .. $FF = 100% base rate)
; ------------------------------------------------------------------------------

MegaPCM_SetActiveSamplePitch:
	MPCM_setPitch	d0
	rts
